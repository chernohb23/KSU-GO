import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const appRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const threeBuild = join(appRoot, 'node_modules', 'three', 'build');
const corePath = join(threeBuild, 'three.core.min.js');
const modulePath = join(threeBuild, 'three.module.min.js');
const outputPath = join(appRoot, 'src', 'three-source.ts');

const [coreSource, moduleSource] = await Promise.all([
  readFile(corePath, 'utf8'),
  readFile(modulePath, 'utf8'),
]);
const moduleImports = [...moduleSource.matchAll(/import\{[^}]+\}from(["'])([^"']+)\1;/g)];

if (moduleImports.length === 0 || moduleImports.some((match) => match[2] !== './three.core.min.js')) {
  throw new Error('Expected the three.js module to import only ./three.core.min.js.');
}

if (/\bimport\s*\{/.test(coreSource)) {
  throw new Error('Expected three.core.min.js to have no module imports.');
}

const safeSource = (source) => source.replace(/<\/script/gi, '<\\/script');

await writeFile(
  outputPath,
  [
    '// Generated by scripts/embed-three.mjs. Do not edit.',
    `export const THREE_CORE_SOURCE = ${JSON.stringify(safeSource(coreSource))};`,
    `export const THREE_MODULE_SOURCE = ${JSON.stringify(safeSource(moduleSource))};`,
    '',
  ].join('\n'),
);
